/// A drug-reference database used by the Medicine Info lookup feature. Each
/// entry is one specific brand (so combo products with a different generic
/// than their "parent" drug — e.g. Arinac vs Brufen — are represented
/// accurately). This lets the pharmacist type the medicine name a patient
/// asked for by its common brand name (e.g. "Brufen") and instantly see
/// general clinical reference info (category, dosage form, strength, usage,
/// dosage, overdose risks, precautions), even if that exact brand isn't in
/// the store's own inventory yet.
///
/// This is general reference information only (comparable to what's
/// printed on a package insert / leaflet) — it is NOT a prescription and
/// always carries a disclaimer in the UI telling the pharmacist to
/// confirm with the doctor and product leaflet.
///
/// Kept in sync with the "Medicine Reference (A-Z)" sheet of the companion
/// Pharmacy_Medicine_Reference.xlsx workbook.
library medicine_reference;

