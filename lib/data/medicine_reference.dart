/// Normalizes text for matching (lowercase, trimmed).
String _norm(String s) => s.trim().toLowerCase();

/// Looks up a single best-match drug reference entry by brand name,
/// generic name, or partial match. Returns null if nothing reasonably
/// matches.
DrugInfo? lookupDrugInfo(String query) {
  final q = _norm(query);
  if (q.isEmpty) return null;

  // 1) Exact brand match first (this is what a patient/pharmacist usually
  // types), then exact generic match.
  for (final d in kDrugReferenceDatabase) {
    if (_norm(d.brandName) == q) return d;
  }
  for (final d in kDrugReferenceDatabase) {
    if (_norm(d.genericName) == q) return d;
  }

  // 2) Partial / contains match (either direction) as a fallback.
  for (final d in kDrugReferenceDatabase) {
    if (_norm(d.brandName).contains(q) || q.contains(_norm(d.brandName))) {
      return d;
    }
  }
  for (final d in kDrugReferenceDatabase) {
    if (_norm(d.genericName).contains(q) || q.contains(_norm(d.genericName))) {
      return d;
    }
  }

  return null;
}

/// Returns up to [limit] suggestions matching the query, for autocomplete.
/// Matches against brand name first, then generic name, so searching a
/// generic (e.g. "Ibuprofen") surfaces every brand that contains it
/// (e.g. Brufen).
List<DrugInfo> suggestDrugInfo(String query, {int limit = 6}) {
  final q = _norm(query);
  if (q.isEmpty) return [];
  final matches = <DrugInfo>[];
  for (final d in kDrugReferenceDatabase) {
    final hit = _norm(d.brandName).contains(q) || _norm(d.genericName).contains(q);
    if (hit) matches.add(d);
    if (matches.length >= limit) break;
  }
  return matches;
}
